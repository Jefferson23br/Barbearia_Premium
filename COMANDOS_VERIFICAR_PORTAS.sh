#!/bin/bash
# Script para verificar portas 80 e 443 antes de configurar SSL

echo "═══════════════════════════════════════════════════"
echo "  🔍 VERIFICAÇÃO DE PORTAS 80 e 443"
echo "═══════════════════════════════════════════════════"
echo ""

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "1️⃣  VERIFICANDO PORTA 80 (HTTP)"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""
echo "📊 Usando 'ss':"
sudo ss -tlnp | grep :80 || echo "   ✅ Porta 80 está LIVRE"
echo ""
echo "📊 Usando 'netstat':"
sudo netstat -tlnp | grep :80 || echo "   ✅ Porta 80 está LIVRE"
echo ""

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "2️⃣  VERIFICANDO PORTA 443 (HTTPS)"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""
echo "📊 Usando 'ss':"
sudo ss -tlnp | grep :443 || echo "   ✅ Porta 443 está LIVRE"
echo ""
echo "📊 Usando 'netstat':"
sudo netstat -tlnp | grep :443 || echo "   ✅ Porta 443 está LIVRE"
echo ""

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "3️⃣  STATUS DOS SERVIÇOS"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""
echo "📦 Status do Nginx:"
sudo systemctl status nginx --no-pager -l | head -5
echo ""
echo "📦 Status do OpenLiteSpeed:"
sudo systemctl status lsws --no-pager -l | head -5
echo ""

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "4️⃣  TODAS AS PORTAS EM USO"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""
echo "📊 Portas do Nginx:"
sudo ss -tlnp | grep nginx || echo "   ℹ️  Nginx não está escutando em nenhuma porta"
echo ""
echo "📊 Portas do OpenLiteSpeed:"
sudo ss -tlnp | grep litespeed || echo "   ℹ️  OpenLiteSpeed não encontrado"
echo ""

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "5️⃣  VIRTUAL HOSTS DO OPENLITESPEED"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""
echo "📁 VHosts existentes:"
sudo ls -la /usr/local/lsws/conf/vhosts/ 2>/dev/null | grep -E "^d|api" || echo "   ℹ️  Diretório não encontrado ou sem vHosts"
echo ""
echo "🔍 Verificando vHost da API:"
sudo ls -la /usr/local/lsws/conf/vhosts/ 2>/dev/null | grep api || echo "   ✅ Nenhum vHost da API encontrado no OpenLiteSpeed"
echo ""

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "6️⃣  FIREWALL"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""
echo "🔥 Portas abertas no firewall:"
sudo firewall-cmd --list-ports 2>/dev/null || echo "   ℹ️  Firewall não configurado ou comando não disponível"
echo ""
echo "🔥 Porta 80 aberta?"
sudo firewall-cmd --query-port=80/tcp 2>/dev/null && echo "   ✅ SIM" || echo "   ❌ NÃO"
echo ""
echo "🔥 Porta 443 aberta?"
sudo firewall-cmd --query-port=443/tcp 2>/dev/null && echo "   ✅ SIM" || echo "   ❌ NÃO"
echo ""

echo "═══════════════════════════════════════════════════"
echo "  ✅ VERIFICAÇÃO CONCLUÍDA!"
echo "═══════════════════════════════════════════════════"
echo ""
echo "📋 Copie os resultados acima e envie para análise."
echo ""

